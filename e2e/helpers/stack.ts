/** Open the upload page and wait for the dropzone to be interactive. */
export async function openUpload(page: Page): Promise<void> {
  await page.goto("/upload");
  await expect(
    page.getByRole("button", { name: "Add files: drop documents here or press Enter to browse" }),
  ).toBeVisible();
}

export interface UploadOptions {
  /** Overrides the filename-derived default title. */
  title?: string;
  /** "library" is admin-only and requires a topic. */
  scope?: "personal" | "library";
  /** Library topic name (e.g. "Workplace Policy"). */
  topic?: string;
}

/**
 * Upload one fixture through the UI and wait for the ingestion pipeline to
 * finish. Returns the terminal status line, e.g. "Ready — 3 chunks indexed."
 * (library uploads append "· awaiting SME approval").
 */
export async function uploadAndWaitReady(
  page: Page,
  fileName: string,
  options: UploadOptions = {},
): Promise<string> {
  await openUpload(page);
  const input = page.locator('input[type="file"]');
  await input.setInputFiles(fixture(fileName));

  if (options.title) {
    await page.getByRole("textbox", { name: "Title" }).fill(options.title);
  }
  if (options.scope === "library") {
    // The radios are sr-only inputs inside labels, so click the visible
    // label text within the scope group (clicking the 1px input itself
    // never passes pointer-events hit-testing).
    const scopeGroup = page.getByRole("radiogroup", { name: "Scope" });
    await scopeGroup.getByText("Agency library", { exact: true }).click();
    const topicBox = page.getByRole("combobox", { name: "Library topic" });
    await topicBox.click();
    await page.getByRole("option", { name: options.topic ?? "Workplace Policy" }).click();
  }

  await page.getByRole("button", { name: /upload \d+ files?/i }).click();

  // The demo pipeline finishes in ~1-3s; the UI polls at 1.5s intervals, so
  // give the status line a generous budget. The demo banner is also a
  // role=status, hence the "chunks indexed" text filter.
  const status = page.getByRole("status").filter({ hasText: /chunks? indexed/ });
  await expect(status).toBeVisible({ timeout: 20_000 });
  if (options.scope === "library") {
    await expect(status).toContainText("awaiting SME approval");
  }
  return (await status.innerText()).trim();
}

export interface ChatAnswer {
  answerText: string;
  /** aria-labels of the citation chips, e.g. "Citation 1: press release". */
  citations: string[];
}

/**
 * Start a new conversation and wait until its (empty) transcript fetch has
 * settled before returning. Asking the very first question in a session the
 * instant it is created races the transcript fetch — if that response lands
 * after the answer stream, the page replaces the message list and the
 * streamed answer disappears (it is still persisted server-side). Settling
 * first keeps tests deterministic; the same thing happens when a human sees
 * the empty conversation before typing.
 */
export async function startConversation(
  page: Page,
  buttonName: "New conversation" | "Admin cross-search" = "New conversation",
): Promise<void> {
  const settled = page.waitForResponse(
    (response) =>
      response.url().includes("/api/chat/sessions/") &&
      response.url().endsWith("/messages") &&
      response.request().method() === "GET" &&
      response.status() === 200,
    { timeout: 10_000 },
  );
  await page.getByRole("button", { name: buttonName }).click();
  await settled;
}

/**
 * Type a question into the composer, send it with Enter, and wait for the
 * streamed answer to fully land (the streaming bubble is replaced by the
 * final message only after the SSE stream closes). The caller is responsible
 * for having a settled conversation selected — see startConversation.
 */
export async function askAndWait(
  page: Page,
  question: string,
  timeout = 30_000,
): Promise<ChatAnswer> {
  const log = page.getByRole("log", { name: "Messages" });
  // Assistant bubbles are identified by their "DocSage" byline paragraph.
  const bylines = log.locator("p").filter({ hasText: /^DocSage$/ });
  const before = await bylines.count();

  const composer = page.getByRole("textbox", { name: "Ask a question about your documents" });
  await composer.fill(question);
  await composer.press("Enter");

  await expect
    .poll(() => bylines.count(), { timeout, message: `assistant bubble should appear: ${question}` })
    .toBeGreaterThan(before);

  // Streaming is finished once the stop control is gone and the final bubble
  // has non-empty content. (Fast demo streams may complete before we even
  // sample; polling handles both orders.)
  const byline = bylines.nth(before);
  const content = byline.locator("xpath=following-sibling::div[1]");
  const stop = page.getByRole("button", { name: "Stop generating" });
  await expect
    .poll(async () => {
      if (await stop.isVisible().catch(() => false)) return "";
      return (await content.innerText()).trim();
    }, { timeout, message: `answer should finish streaming: ${question}` })
    .not.toBe("");

  const answerText = (await content.innerText()).trim();
  const chips = byline.locator("xpath=following-sibling::ul[1]").locator('[aria-label^="Citation"]');
  const citations = await chips.evaluateAll((elements) =>
    elements.map((element) => element.getAttribute("aria-label") ?? ""),
  );
  return { answerText, citations };
}
