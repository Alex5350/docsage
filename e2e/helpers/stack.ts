/** Resolve a fixture file by name. */
export function fixture(name: string): string {
  return path.join(FIXTURES_DIR, name);
}

/** Collision-proof identity, safe across re-runs and parallel machines. */
export function uniqueEmail(prefix: string): string {
  return `qa-${prefix}-${Date.now()}-${Math.random().toString(36).slice(2, 7)}@docsage.dev`;
}

/** Register through the /login form and land on /chat. */
export async function registerViaUi(
  page: Page,
  email: string,
  password: string = DEMO_PASSWORD,
  displayName = "QA Checker",
): Promise<void> {
  await page.goto("/login");
  await page.getByRole("tab", { name: "Register" }).click();
  await page.getByRole("textbox", { name: "Display name" }).fill(displayName);
  await page.getByRole("textbox", { name: "Email" }).fill(email);
  await page.getByRole("textbox", { name: "Password" }).fill(password);
  await page.getByRole("button", { name: "Create account" }).click();
  await expect(page).toHaveURL(/\/chat$/, { timeout: 15_000 });
}

